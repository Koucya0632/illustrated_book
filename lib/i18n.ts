const messages: Record<Locale, Dict> = { "zh-Hant": zhHant, "zh-Hans": zhHans };

export function t(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let s = messages[locale]?.[key] ?? zhHant[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}
